namespace Clover.Player.Swings
{
    /// <summary>What an element's trail throws off its head as the blade moves, and what it does when the swing ends.</summary>
    public enum SwingShed
    {
        None,
        /// <summary>Fire: embers off the flame's edge.</summary>
        Embers,
        /// <summary>Lightning: the crackle that jumps from the point.</summary>
        Crackle,
        /// <summary>Ice: the breath of cold, sinking.</summary>
        FrostBreath,
        /// <summary>Earth: grit and dust shaken loose, falling.</summary>
        Grit,
        /// <summary>Life: leaves and pollen torn off and falling away.</summary>
        Leaves,
        /// <summary>Poison: venom dripping off the arc and a heavy mist sinking from it.</summary>
        Drips,
    }
}
